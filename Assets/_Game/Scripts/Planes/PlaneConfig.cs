using System;
using UnityEngine;

namespace Game.Planes
{
    public enum PlaneShape { Dart, SlimDart, WideDart, Glider, WideWing, Delta, Stunt, Swallow, Square }

    public enum PlanePattern { Plain, Lined, Stripes, Newsprint, Map, Comic, Blueprint, Stars, Rainbow, Metallic }

    public enum UnlockKind
    {
        Start,    // owned from the first launch
        Stars,    // total stars ≥ Value
        Level,    // level Value completed (1-based)
        CheckIn,  // Value-th day played
    }

    [Serializable]
    public struct UnlockRule
    {
        public UnlockKind Kind;
        public int Value;

        public UnlockRule(UnlockKind kind, int value)
        {
            Kind = kind;
            Value = value;
        }
    }

    /// <summary>Plane stats, 1-5 each (SPEC §3). 3 = the classic dart.</summary>
    [Serializable]
    public struct PlaneStats
    {
        [Range(1, 5)] public int Speed;
        [Range(1, 5)] public int Agility;
        [Range(1, 5)] public int Glide;
        [Range(1, 5)] public int Lift;
        [Range(1, 5)] public int Stability;

        public PlaneStats(int speed, int agility, int glide, int lift, int stability)
        {
            Speed = speed;
            Agility = agility;
            Glide = glide;
            Lift = lift;
            Stability = stability;
        }

        public static PlaneStats Classic => new PlaneStats(3, 3, 3, 3, 3);
    }

    /// <summary>
    /// One plane in the collection (SPEC §3): look (generated mesh + material + thumbnail), stats that scale the
    /// flight model, and how it unlocks. Generated by PlaneBuilder from a table in code.
    /// </summary>
    [CreateAssetMenu(menuName = "Game/Configs/Plane", fileName = "Plane")]
    public sealed class PlaneConfig : ScriptableObject
    {
        [SerializeField] private string _id = "dart";
        [SerializeField] private string _displayName = "Classic Dart";
        [SerializeField] private PlaneShape _shape;
        [SerializeField] private PlanePattern _pattern;
        [SerializeField] private Color _primary = Color.white;
        [SerializeField] private Color _secondary = new Color(0.3f, 0.6f, 1f);
        [SerializeField] private PlaneStats _stats = PlaneStats.Classic;
        [SerializeField] private UnlockRule _unlock;
        [SerializeField] private Mesh _mesh;
        [SerializeField] private Material _material;
        [SerializeField] private Sprite _thumbnail;

        public string Id => _id;
        public string DisplayName => _displayName;
        public PlaneShape Shape => _shape;
        public PlanePattern Pattern => _pattern;
        public Color Primary => _primary;
        public Color Secondary => _secondary;
        public PlaneStats Stats => _stats;
        public UnlockRule Unlock => _unlock;
        public Mesh Mesh => _mesh;
        public Material Material => _material;
        public Sprite Thumbnail => _thumbnail;

#if UNITY_EDITOR
        public void Define(string id, string displayName, PlaneShape shape, PlanePattern pattern, Color primary,
            Color secondary, PlaneStats stats, UnlockRule unlock)
        {
            _id = id;
            _displayName = displayName;
            _shape = shape;
            _pattern = pattern;
            _primary = primary;
            _secondary = secondary;
            _stats = stats;
            _unlock = unlock;
        }

        public void SetLook(Mesh mesh, Material material, Sprite thumbnail)
        {
            _mesh = mesh;
            _material = material;
            if (thumbnail != null) _thumbnail = thumbnail;
        }
#endif
    }
}
